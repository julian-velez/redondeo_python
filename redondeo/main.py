import math  # Importa el módulo 'math', que contiene funciones matemáticas como floor, ceil, sqrt, etc.

print(math.floor(3.7))  # 'math.floor()' redondea hacia abajo el número 3.7, 
                        # es decir, devuelve el entero más pequeño menor o igual a 3.7 → resultado: 3

print(math.ceil(3.3))   # 'math.ceil()' redondea hacia arriba el número 3.3, 
                        # es decir, devuelve el entero más grande mayor o igual a 3.3 → resultado: 4
